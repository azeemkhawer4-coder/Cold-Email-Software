let dbCache: DatabaseSchema | null = null;

export function getDatabase(): DatabaseSchema {
  if (dbCache) return dbCache;

  try {
    if (fs.existsSync(DB_PATH)) {
      const raw = fs.readFileSync(DB_PATH, 'utf-8');
      dbCache = JSON.parse(raw);
      if (!dbCache!.sendingJobs) dbCache!.sendingJobs = [];
      if (!dbCache!.failureReports) dbCache!.failureReports = [];
      if (!dbCache!.sendingEvents) dbCache!.sendingEvents = [];
      if (!dbCache!.suppressionList) dbCache!.suppressionList = [];
      return dbCache!;
    }
  } catch (err) {
    console.error('Error reading OutboundOS database, recreating seed:', err);
  }

  const initial = createInitialSeed();
  saveDatabase(initial);
  return initial;
}

export function saveDatabase(data: DatabaseSchema): void {
  try {
    const dir = path.dirname(DB_PATH);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(DB_PATH, JSON.stringify(data, null, 2), 'utf-8');
    dbCache = data;
  } catch (err) {
    console.error('Failed to save OutboundOS database:', err);
  }
}
